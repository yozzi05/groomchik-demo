export const serviceById = (id: string | undefined) => services.find((s) => s.id === id)

export const servicesFor = (species: Species) => services.filter((s) => s.species.includes(species))

export function plural(n: number, one: string, few: string, many: string) {
  const a = Math.abs(n) % 100
  const b = a % 10
  if (a > 10 && a < 20) return many
  if (b > 1 && b < 5) return few
  if (b === 1) return one
  return many
}
export const bonusesText = (n: number) => `${n} ${plural(n, 'бонус', 'бонуса', 'бонусов')}`

